#!/usr/bin/env bash
# Extract the bundle first, then run: sudo ./install.sh
# This script never performs apt update, apt downloads, image pulls, or builds.
set -Eeuo pipefail
umask 077
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
cd "$ROOT"
fail() { printf '\nERROR: %s\n' "$*" >&2; exit 1; }
trap 'rc=$?; if ((rc != 0)); then printf "\nINSTALLATION FAILED (exit %s, line %s).\n" "$rc" "$LINENO" >&2; printf "See: docker-compose logs --tail=100 platform (after Docker is running)\n" >&2; fi' EXIT

[[ "$(id -u)" -eq 0 ]] || fail "Run with sudo: sudo ./install.sh"
[[ -f /etc/os-release ]] || fail "Cannot identify target OS."
# Verify every staged file before modifying the target.
[[ -f SHA256SUMS ]] || fail "Missing SHA256SUMS."
sha256sum -c SHA256SUMS
for f in images.tar docker-compose.yml .env.enc build-os-release base-packages.tsv install.sh target-platform.txt; do
  [[ -f "$ROOT/$f" ]] || fail "Missing bundle file: $f"
done
[[ -d "$ROOT/docker-install/debs" ]] || fail "Missing docker-install/debs."
[[ "$(cat "$ROOT/target-platform.txt")" == "linux/amd64" ]] || fail "Bundle is not tagged linux/amd64."

# Compare the clean target base with the builder fingerprint before installing
# anything. Exact key-package versions provide a useful update-level guard.
# shellcheck disable=SC1091
. /etc/os-release
TARGET_ID="${ID:-}"
TARGET_VERSION_ID="${VERSION_ID:-}"
# build-os-release is generated by our own preparation script.
# shellcheck disable=SC1090
. "$ROOT/build-os-release"
BUILD_ID="${ID:-}"
BUILD_VERSION_ID="${VERSION_ID:-}"
[[ "$TARGET_ID" == "astra" && "$TARGET_ID" == "$BUILD_ID" ]] || fail "OS ID mismatch: target=$TARGET_ID bundle=$BUILD_ID; expected Astra Linux."
[[ -n "$TARGET_VERSION_ID" && "$TARGET_VERSION_ID" == "$BUILD_VERSION_ID" ]] || fail "Astra VERSION_ID mismatch: target=$TARGET_VERSION_ID bundle=$BUILD_VERSION_ID. Use a matching Astra 1.7 release."

[[ -f "$ROOT/base-packages.tsv" ]] || fail "Missing base package fingerprint."
while IFS=$'\t' read -r pkg wanted; do
  [[ "$pkg" == "package" || -z "$pkg" ]] && continue
  actual="$(dpkg-query -W -f='${Version}' "$pkg" 2>/dev/null || true)"
  [[ -n "$actual" ]] || fail "Target base package '$pkg' is absent but was present on the builder. This target is not the matching clean baseline."
  [[ "$actual" == "$wanted" ]] || fail "Base package mismatch for $pkg: target=$actual bundle-baseline=$wanted. Rebuild for this exact Astra update level."
done < "$ROOT/base-packages.tsv"
printf '\nTARGET BASELINE VERIFIED: Astra %s, amd64, key package versions match.\n' "$TARGET_VERSION_ID"

shopt -s nullglob
packages=("$ROOT/docker-install/debs"/*.deb)
((${#packages[@]} > 0)) || fail "No local .deb files are available."
command -v apt-get >/dev/null || fail "apt-get is unavailable."
printf '\nInstalling Docker/Compose exclusively from bundled .deb files (no downloads)...\n'
DEBIAN_FRONTEND=noninteractive apt-get --no-download --yes install "${packages[@]}" || \
  fail "Local package installation failed. The bundle may lack a dependency or this target does not match the build baseline. No dependency download was permitted."

command -v systemctl >/dev/null || fail "systemctl is unavailable."
command -v docker >/dev/null || fail "Bundled packages did not install docker."
command -v docker-compose >/dev/null || fail "Bundled packages did not install the required docker-compose command."
docker --version
compose_version="$(docker-compose version 2>&1)"
printf '%s\n' "$compose_version"
grep -Eiq '(^|[^0-9])v?2\.[0-9]+\.[0-9]+' <<<"$compose_version" || fail "docker-compose is not Compose v2; expected --pull never and --no-build support."
up_help="$(docker-compose up --help 2>&1)"
grep -q -- '--pull' <<<"$up_help" || fail "docker-compose up lacks --pull support."
grep -q -- '--no-build' <<<"$up_help" || fail "docker-compose up lacks --no-build support."

# Decrypt to the runtime .env only after integrity and OS-package checks.
# Existing .env is retained on reruns and is never overwritten automatically.
if [[ -e "$ROOT/.env" ]]; then
  [[ -s "$ROOT/.env" ]] || fail "An empty .env already exists; refusing to overwrite it."
  chmod 0600 "$ROOT/.env"
  printf '\nUsing existing .env in the extracted bundle directory (not from the ZIP).\n'
else
  command -v openssl >/dev/null || fail "openssl is not available after bundled package installation."
  read -r -s -p 'Enter passphrase used to encrypt .env: ' env_pass; printf '\n'
  [[ -n "$env_pass" ]] || fail "Empty passphrase is not allowed."
  tmp_env="$ROOT/.env.tmp.$$"
  if ! printf '%s' "$env_pass" | openssl enc -d -aes-256-cbc -pbkdf2 -iter 250000 -pass stdin \
      -in "$ROOT/.env.enc" -out "$tmp_env"; then
    rm -f -- "$tmp_env"; unset env_pass; fail "Could not decrypt .env. Check the passphrase."
  fi
  unset env_pass
  [[ -s "$tmp_env" ]] || { rm -f -- "$tmp_env"; fail "Decrypted .env is empty. Refusing to continue."; }
  chmod 0600 "$tmp_env"
  mv -- "$tmp_env" "$ROOT/.env"
fi

systemctl enable --now docker || fail "Docker daemon failed to start. Check Astra security policy and journalctl -u docker."
docker info >/dev/null || fail "Docker daemon is not responding."
printf '\nLoading the three pre-exported local images...\n'
docker image load --input "$ROOT/images.tar"
for img in radp:latest postgres:17 mcuadros/ofelia:latest; do
  docker image inspect "$img" >/dev/null || fail "Required local image missing after image load: $img"
  os="$(docker image inspect --format '{{.Os}}' "$img")"
  arch="$(docker image inspect --format '{{.Architecture}}' "$img")"
  [[ "$os/$arch" == "linux/amd64" ]] || fail "$img platform is $os/$arch, expected linux/amd64."
done

# Static safety checks before Compose starts anything.
if grep -Eq '^[[:space:]]*build[[:space:]]*:' "$ROOT/docker-compose.yml"; then
  fail "docker-compose.yml contains a build: section; offline bundle must use prebuilt images only."
fi
policy_count="$(grep -Ec '^[[:space:]]*pull_policy:[[:space:]]*never[[:space:]]*$' "$ROOT/docker-compose.yml" || true)"
((policy_count >= 4)) || fail "Expected pull_policy: never on all four Compose services; found $policy_count entries."
for image in radp:latest postgres:17 mcuadros/ofelia:latest; do
  grep -Fq "$image" "$ROOT/docker-compose.yml" || fail "docker-compose.yml does not refer to required image $image."
done
for service in postgres db-init platform scheduler; do
  # Catch an accidentally omitted no-pull policy on a service declaration.
  : # Compose config and the explicit --pull never flag are final safeguards.
done
docker-compose config -q || fail "docker-compose.yml/.env validation failed."

printf '\nStarting RADP with local images only...\n'
docker-compose up -d --pull never --no-build || fail "Compose startup failed. No image pulls or builds were allowed."

# Wait for required containers. The init container must finish successfully;
# the three long-running containers must stay running.
wait_running() {
  local name="$1" seconds="${2:-180}" elapsed=0 state
  while ((elapsed < seconds)); do
    state="$(docker inspect --format '{{.State.Status}}' "$name" 2>/dev/null || true)"
    [[ "$state" == "running" ]] && return 0
    [[ "$state" == "exited" || "$state" == "dead" ]] && {
      docker logs --tail=80 "$name" >&2 || true
      fail "Container $name ended in state '$state'."
    }
    sleep 2; elapsed=$((elapsed + 2))
  done
  docker logs --tail=80 "$name" >&2 || true
  fail "Timed out waiting for container $name to run."
}
wait_init_success() {
  local name="$1" seconds="${2:-180}" elapsed=0 status exit_code
  while ((elapsed < seconds)); do
    status="$(docker inspect --format '{{.State.Status}}' "$name" 2>/dev/null || true)"
    if [[ "$status" == "exited" ]]; then
      exit_code="$(docker inspect --format '{{.State.ExitCode}}' "$name")"
      [[ "$exit_code" == "0" ]] && return 0
      docker logs --tail=100 "$name" >&2 || true
      fail "Initialization container $name exited with code $exit_code."
    fi
    [[ "$status" == "dead" ]] && fail "Initialization container $name is dead."
    sleep 2; elapsed=$((elapsed + 2))
  done
  docker logs --tail=100 "$name" >&2 || true
  fail "Timed out waiting for initialization container $name to complete."
}
wait_running radp-postgres
wait_running radp-platform
wait_running radp-scheduler
wait_init_success radp-db-init

# Confirm PostgreSQL accepts connections and RADP listens on its published port.
pg_ready=0
for _ in $(seq 1 90); do
  if docker exec radp-postgres pg_isready >/dev/null 2>&1; then pg_ready=1; break; fi
  sleep 2
done
((pg_ready == 1)) || { docker logs --tail=100 radp-postgres >&2 || true; fail "PostgreSQL did not become ready."; }
api_ready=0
for _ in $(seq 1 90); do
  if (exec 3<>/dev/tcp/127.0.0.1/9000) >/dev/null 2>&1; then api_ready=1; break; fi
  sleep 2
done
((api_ready == 1)) || { docker logs --tail=100 radp-platform >&2 || true; fail "RADP is running but port 9000 did not accept TCP connections."; }

printf '\n'
docker-compose ps
printf '\nDEPLOYMENT SUCCESS\n'
printf 'Verified: local images loaded; Compose ran with --pull never --no-build; postgres ready; db-init exited 0; platform port 9000 accepts TCP; scheduler running.\n'
printf 'OFFLINE PORTABILITY STATUS: only confirmed if this installation was run on a clean matching Astra VM with its virtual NIC disconnected. The script cannot independently prove the VM has no network connectivity.\n'
printf '\nUseful diagnostics:\n  cd %q && docker-compose logs --tail=100 platform\n  cd %q && docker-compose logs --tail=100 postgres\n' "$ROOT" "$ROOT"
